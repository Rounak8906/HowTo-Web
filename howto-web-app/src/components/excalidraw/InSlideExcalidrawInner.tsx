'use client';

import React, { useState, useEffect, useCallback } from 'react';
import { Excalidraw, exportToSvg } from '@excalidraw/excalidraw';
import '@excalidraw/excalidraw/index.css';
import styles from './excalidraw.module.css';
import type { SlideElement } from '@/lib/types';

export interface InSlideSavePayload {
  svgString: string;
  elements: readonly any[];
  appState: any;
  files: any;
  name: string;
}

export interface InSlideExcalidrawProps {
  element: SlideElement;
  onSave: (payload: InSlideSavePayload) => void;
  onCancel: () => void;
  onToggleFullSlide?: () => void;
  isFullSlide?: boolean;
}

export default function InSlideExcalidrawInner({
  element,
  onSave,
  onCancel,
  onToggleFullSlide,
  isFullSlide = false,
}: InSlideExcalidrawProps) {
  const [excalidrawAPI, setExcalidrawAPI] = useState<any>(null);
  const [diagramName, setDiagramName] = useState<string>(
    element.diagramName || 'Hand-drawn Diagram'
  );
  const [theme, setTheme] = useState<'dark' | 'light'>(
    element.excalidrawAppState?.theme || 'dark'
  );
  const [transparentBg, setTransparentBg] = useState<boolean>(true);
  const [isExporting, setIsExporting] = useState<boolean>(false);

  // Restore initial scene elements when Excalidraw mounts
  useEffect(() => {
    if (excalidrawAPI && element) {
      if (element.excalidrawElements && element.excalidrawElements.length > 0) {
        excalidrawAPI.updateScene({
          elements: element.excalidrawElements,
          appState: {
            ...element.excalidrawAppState,
            theme,
          },
        });
        if (element.excalidrawFiles) {
          excalidrawAPI.addFiles(Object.values(element.excalidrawFiles));
        }
      }
    }
  }, [excalidrawAPI, element, theme]);

  const handleExportAndSave = useCallback(async () => {
    if (!excalidrawAPI) return;
    setIsExporting(true);

    try {
      const elements = excalidrawAPI.getSceneElements();
      const appState = excalidrawAPI.getAppState();
      const files = excalidrawAPI.getFiles();

      if (!elements || elements.length === 0) {
        onSave({
          svgString: '',
          elements: [],
          appState: { theme },
          files: {},
          name: diagramName.trim() || 'Hand-drawn Diagram',
        });
        return;
      }

      // Generate clean vector SVG
      const svgElement = await exportToSvg({
        elements,
        appState: {
          ...appState,
          exportWithDarkMode: theme === 'dark',
          exportBackground: !transparentBg,
          viewBackgroundColor: transparentBg
            ? 'transparent'
            : appState.viewBackgroundColor || '#0f1422',
          exportPadding: 16,
        },
        files,
      });

      // If transparent, remove any solid background rectangle generated by Excalidraw
      if (transparentBg) {
        const firstRect = svgElement.querySelector('rect');
        if (firstRect) {
          const w = firstRect.getAttribute('width');
          const h = firstRect.getAttribute('height');
          const fill = firstRect.getAttribute('fill')?.toLowerCase();
          // If this is a full-canvas background rect
          if (
            (fill === '#ffffff' || fill === '#fff' || fill === 'rgb(255, 255, 255)' || fill === '#121212' || fill === '#000000' || fill === 'transparent') &&
            w && h
          ) {
            firstRect.remove();
          }
        }
      }

      svgElement.setAttribute('width', '100%');
      svgElement.setAttribute('height', '100%');
      svgElement.setAttribute('preserveAspectRatio', 'xMidYMid meet');
      svgElement.style.display = 'block';
      svgElement.style.background = 'transparent';

      const serializer = new XMLSerializer();
      const svgString = serializer.serializeToString(svgElement);

      onSave({
        svgString,
        elements,
        appState: {
          theme,
          viewBackgroundColor: appState.viewBackgroundColor,
          gridSize: appState.gridSize,
        },
        files,
        name: diagramName.trim() || 'Hand-drawn Diagram',
      });
    } catch (err) {
      console.error('Failed to export in-slide Excalidraw:', err);
      alert('Error exporting diagram. Please try again.');
    } finally {
      setIsExporting(false);
    }
  }, [excalidrawAPI, theme, transparentBg, diagramName, onSave]);

  const isNearTop = (element.y || 0) < 12 || isFullSlide;

  return (
    <div
      className={styles.inSlideWrapper}
      onMouseDown={(e) => e.stopPropagation()}
      onClick={(e) => e.stopPropagation()}
      onPointerDown={(e) => e.stopPropagation()}
      onKeyDown={(e) => e.stopPropagation()}
      style={{
        background: transparentBg ? 'rgba(15, 20, 34, 0.9)' : (theme === 'dark' ? '#121726' : '#ffffff'),
      }}
    >
      {/* Floating In-Slide Header Bar */}
      <div
        className={styles.inSlideFloatingBar}
        style={{ top: isNearTop ? '8px' : '-46px' }}
        onMouseDown={(e) => e.stopPropagation()}
      >
        <div className={styles.inSlideBarLeft}>
          <span className={styles.inSlideBadge}>✏️ Drawing on Slide</span>
          <input
            type="text"
            className={styles.inSlideTitleInput}
            value={diagramName}
            onChange={(e) => setDiagramName(e.target.value)}
            placeholder="Diagram name..."
            title="Diagram Title"
          />
        </div>

        <div className={styles.inSlideBarRight}>
          <button
            type="button"
            className={`${styles.inSlideBtn} ${theme === 'dark' ? styles.inSlideBtnActive : ''}`}
            onClick={() => {
              const nextTheme = theme === 'dark' ? 'light' : 'dark';
              setTheme(nextTheme);
              if (excalidrawAPI) {
                excalidrawAPI.updateScene({ appState: { theme: nextTheme } });
              }
            }}
            title="Toggle Dark / Light Canvas Mode"
          >
            <span>{theme === 'dark' ? '🌙 Dark' : '☀️ Light'}</span>
          </button>

          <button
            type="button"
            className={`${styles.inSlideBtn} ${transparentBg ? styles.inSlideBtnActive : ''}`}
            onClick={() => setTransparentBg(!transparentBg)}
            title="Toggle transparent or solid background for slide"
          >
            <span>{transparentBg ? '◻ Transparent' : '◼ Solid'}</span>
          </button>

          {onToggleFullSlide && (
            <button
              type="button"
              className={`${styles.inSlideBtn} ${isFullSlide ? styles.inSlideBtnActive : ''}`}
              onClick={onToggleFullSlide}
              title={isFullSlide ? 'Restore to Boxed Element' : 'Expand Drawing across Full Slide'}
            >
              <span>{isFullSlide ? '⤡ Boxed' : '⤢ Full Slide'}</span>
            </button>
          )}

          <button
            type="button"
            className={styles.inSlideCancelBtn}
            onClick={onCancel}
            title="Cancel editing"
          >
            Cancel
          </button>

          <button
            type="button"
            className={styles.inSlideDoneBtn}
            onClick={handleExportAndSave}
            disabled={isExporting}
            title="Save diagram directly on this slide"
          >
            <span>{isExporting ? '⏳ Saving...' : '✅ Done Drawing'}</span>
          </button>
        </div>
      </div>

      {/* Embedded Excalidraw Engine */}
      <div className={styles.inSlideCanvasArea}>
        <Excalidraw
          excalidrawAPI={(api: any) => setExcalidrawAPI(api)}
          theme={theme}
          UIOptions={{
            canvasActions: {
              loadScene: false,
              saveToActiveFile: false,
              export: false,
              saveAsImage: false,
            },
          }}
        />
      </div>
    </div>
  );
}
